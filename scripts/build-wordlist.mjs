#!/usr/bin/env node
/**
 * Regenerates lib/games/words.ts from a system word list.
 *
 *   node scripts/build-wordlist.mjs [path-to-wordlist]
 *
 * Defaults to /usr/share/dict/words (the public-domain Webster's Second International list, `web2`,
 * on macOS and most BSDs). Keeps lower-case entries of 3–7 letters, deduplicated and sorted.
 *
 * The list is checked in, so this only needs re-running if the accepted vocabulary changes.
 * Regenerating it changes which words score, so treat it as a gameplay change, not a chore.
 */
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2] ?? "/usr/share/dict/words";
const target = join(root, "lib/games/words.ts");

let raw;
try {
  raw = readFileSync(source, "utf8");
} catch {
  console.error(`Could not read ${source}. Pass a word-list path as the first argument.`);
  process.exit(1);
}

const words = [...new Set(raw.split("\n").filter((w) => /^[a-z]{3,7}$/.test(w)))].sort();

const file = `/**
 * Word list for Word Hunt, derived from the public-domain Webster's Second International word
 * list shipped as \`/usr/share/dict/words\` (\`web2\`), filtered to lower-case entries of 3–7
 * letters. Generated by scripts/build-wordlist.mjs — do not edit by hand.
 *
 * Stored as one space-separated string rather than an array of quoted strings: it is roughly a
 * third of the bytes before compression, and this module is lazy-loaded with the Word Hunt chunk
 * so it never touches the entry bundle.
 */

const RAW =
  "${words.join(" ")}";

/** Set of every accepted word, upper-case. Built once on first import. */
export const WORD_SET: ReadonlySet<string> = new Set(RAW.split(" ").map((w) => w.toUpperCase()));

export const MIN_WORD_LENGTH = 3;
export const MAX_WORD_LENGTH = 7;
`;

writeFileSync(target, file);
console.log(`Wrote ${words.length} words to lib/games/words.ts (${(statSync(target).size / 1024).toFixed(0)} KB)`);
